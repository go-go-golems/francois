#!/usr/bin/env bash
# Seed the local compose storefront (http://localhost:8090) through the studio
# API with a personal token: creators, three artifact pages, journal posts.
# Needs plans "subscriber" and "studio" in the settings, releases of polis,
# capabilities and tessera, and the screenshots named below in $SHOWCASE_DIR/shots.
# Local use only.
set -euo pipefail
SP=${SHOWCASE_DIR:?set SHOWCASE_DIR to a directory with showcase.token and shots/}
S=http://localhost:8090
T=$(cat "$SP/showcase.token")
SH=$SP/shots
api() { # method path [json]
  local out
  out=$(curl -sS -X "$1" -H "Authorization: Bearer $T" -H 'Content-Type: application/json' ${3:+--data-binary "$3"} -w '\n%{http_code}' "$S$2")
  local code=${out##*$'\n'}
  if [[ $code -ge 300 ]]; then echo "FAIL $1 $2 -> $code ${out%$'\n'*}" >&2; exit 1; fi
  printf '%s' "${out%$'\n'*}"
}
media() { curl -sS -H "Authorization: Bearer $T" -F "file=@$1" -F "alt=$2" "$S/api/studio/media" | jq -r .id; }

M_AV_MANUEL=$(media "$SH/avatar-manuel.png" "Manuel")
M_AV_RAMON=$(media "$SH/avatar-ramon.png" "Ramon")
M_POLIS_NIGHT=$(media "$SH/polis-live.png" "Night City: the live layer lights windows and flies aircraft between towers")
M_POLIS_METRO=$(media "$SH/polis-metropolis.png" "Metropolis: 423 towers, skybridges and the Tower of Babel")
M_POLIS_FACADES=$(media "$SH/polis-facades.png" "Façades generated by wave function collapse")
M_POLIS_GRID=$(media "$SH/polis-grid.png" "The same pipeline on a square grid")
M_POLIS_ONE=$(media "$SH/polis-1.png" "Preset 01: one tower, ten lines of code")
M_POLIS_PLATE=$(media "$SH/polis-night-plate.png" "Night City plate")
M_TESS_ARCS=$(media "$SH/tessera-arcs.png" "Arcs on paper, 18 × 18")
M_TESS_NIGHT=$(media "$SH/tessera-weave-night.png" "Weave on the night palette")
M_TESS_OCHRE=$(media "$SH/tessera-diag-ochre.png" "Diagonals in ochre, 26 × 26")
M_CAPS=$(media "$SH/caps-cover.png" "The shared board with four tasks")
echo "media uploaded"

C_MANUEL=$(api POST /api/studio/creators "$(jq -n --arg av "$M_AV_MANUEL" '{slug:"manuel",name:"Manuel",sortOrder:0,avatar:$av,
  bio:"Builds tools for thinking with language models. Polis started as a question: what if the agent edited the program, not the picture?",
  links:[{label:"scapegoat.dev",url:"https://scapegoat.dev"},{label:"GitHub",url:"https://github.com/wesen"}]}')" | jq -r .id)
C_RAMON=$(api POST /api/studio/creators "$(jq -n --arg av "$M_AV_RAMON" '{slug:"ramon",name:"Ramon",sortOrder:1,avatar:$av,
  bio:"Designs interfaces that stay out of the way. Likes engraving, grids and type that does not shout.",links:[]}')" | jq -r .id)
echo "creators $C_MANUEL $C_RAMON"

page() { # artifact body cover gallery-json
  api PUT "/api/studio/artifacts/$1/draft" "$(jq -n --arg b "$2" --arg c "$3" --argjson g "$4" '{body:$b,cover:$c,gallery:$g}')" >/dev/null
  api POST "/api/studio/artifacts/$1/draft/publish" >/dev/null
}

# Polis: featured, free sample, demo.
api PATCH /api/studio/artifacts/polis "$(jq -n --arg m "$C_MANUEL" --arg r "$C_RAMON" '{title:"Polis IDE",
  description:"A parametric 3D city IDE with an agent that edits the program, not the picture.",
  tags:["3d","agents","generative"],featured:true,sortOrder:0,requiredPlan:"subscriber",demoEnabled:true,creators:[$m,$r]}')" >/dev/null
page polis "$(cat <<EOF
Polis is a small city-building language and the IDE around it. A scene is a **program**: a lattice, a few masses, a stack of rules and a look. Change a slider and only the stages that depend on it rebuild; change a line and the city redraws in milliseconds.

![Metropolis](/media/$M_POLIS_METRO)

## The agent edits the program

The chat on the left does not paint pixels. It has one tool, \`eval()\`, which runs JavaScript in the page with the Polis DSL and the editor in scope. Ask it to *make the towers taller near the centre and add thirty aircraft* and it rewrites the program; you see the diff in the editor and the result on the plate.

- Ten presets walk from a single tower to a full metropolis.
- Façades come from wave function collapse over wall segments.
- The live layer animates lights and aircraft without rebuilding geometry.

## Try it three ways

| | What you get |
|---|---|
| **Demo** | A 30-minute private instance, no account needed |
| **Free sample** | Download v1.1.0 as one HTML file and run it anywhere |
| **Subscriber** | Your own instances, saved presets and the agent with monthly credits |

![Night City plate](/media/$M_POLIS_PLATE)
EOF
)" "$M_POLIS_NIGHT" "$(jq -n --arg a "$M_POLIS_METRO" --arg b "$M_POLIS_FACADES" --arg c "$M_POLIS_GRID" --arg d "$M_POLIS_ONE" '[$a,$b,$c,$d]')"
echo "polis page published"

# Capabilities: subscriber plan, by Ramon, with a pending draft.
api PATCH /api/studio/artifacts/capabilities "$(jq -n --arg r "$C_RAMON" '{title:"Capability playground",
  description:"A shared board that shows every runtime capability: documents, rooms, presence, assets and comments.",
  tags:["tools","collaboration"],featured:false,sortOrder:2,requiredPlan:"subscriber",creators:[$r]}')" >/dev/null
CAPS_BODY="The playground is the smallest application that touches every capability an instance offers. Open it in two tabs and watch tasks, presence and reactions move between them.

## What it exercises

1. **Documents**: tasks are rows in the instance database.
2. **Rooms and presence**: the tab counter and reactions travel over a room.
3. **Comments**: threads attach to the board.
4. **Assets and downloads**: *Export JSON* writes a file you can keep.

Use it as a template: everything is in one HTML file and the manifest lists what it asks for."
page capabilities "$CAPS_BODY" "$M_CAPS" '[]'
api PUT /api/studio/artifacts/capabilities/draft "$(jq -n --arg b "$CAPS_BODY

## Coming next (draft)

A *Members* panel that lists who is in the room and what they last touched. This paragraph is only visible in the draft preview." --arg c "$M_CAPS" '{body:$b,cover:$c,gallery:[]}')" >/dev/null
echo "capabilities page published, draft pending"

# Tessera: top tier.
api PATCH /api/studio/artifacts/tessera "$(jq -n --arg m "$C_MANUEL" --arg r "$C_RAMON" '{featured:true,sortOrder:1,requiredPlan:"studio",creators:[$r,$m]}')" >/dev/null
page tessera "$(cat <<EOF
Tessera makes engraved Truchet plates. Each cell holds the same tile, turned or not; the whole pattern is a grid, a seed and a bias. Hatching lines give the tiles the weight of an etching.

![Weave on the night palette](/media/$M_TESS_NIGHT)

## Controls

- **Motif**: arcs, diagonals or a woven curve.
- **Grid** from 6 × 6 to 40 × 40, **seed**, and **bias** (how many tiles turn).
- **Hatching** and **line weight** for the engraving.
- **Save PNG** exports the plate at 1200 × 1200.

Tessera is part of the **Studio** plan, together with higher model limits and more instances.
EOF
)" "$M_TESS_ARCS" "$(jq -n --arg a "$M_TESS_NIGHT" --arg b "$M_TESS_OCHRE" '[$a,$b]')"
echo "tessera page published"

post() { # slug title summary body cover author tags-json publish
  local id
  id=$(api POST /api/studio/posts "$(jq -n --arg s "$1" --arg t "$2" --arg su "$3" --arg b "$4" --arg c "$5" --arg a "$6" --argjson tg "$7" \
    '{slug:$s,title:$t,summary:$su,body:$b,cover:$c,authorId:$a,tags:$tg}')" | jq -r .id)
  [[ $8 == yes ]] && api POST "/api/studio/posts/$id/publish" >/dev/null
  echo "post $1 ($id)"
}
post polis-the-agent-edits-the-program "Polis: the agent edits the program" \
  "Why the Polis agent has exactly one tool, and what that buys you." "$(cat <<EOF
Most 3D tools with an assistant let the model move objects. Polis gives it something narrower and stronger: one tool, \`eval()\`, that runs code against the same DSL you write by hand.

![Façades](/media/$M_POLIS_FACADES)

## One tool

Because the agent writes the program, every change is visible, reversible and yours to keep. Undo is just the editor's undo. A preset the agent saves is a program you can read.

## Incremental rebuilds

The pipeline is a graph: lattice → masses → rules → façades → look. Moving *Density* only rebuilds what depends on it, so the agent can try ten variations in the time a full rebuild would take.

[Run the demo](/apps/polis) or download the free sample from the versions list.
EOF
)" "$M_POLIS_METRO" "$C_MANUEL" '["polis","agents"]' yes
post engraving-on-a-grid "Engraving on a grid" \
  "How Tessera gets an etched look out of one tile and a seed." "$(cat <<EOF
Truchet tiles are old: one square tile with two quarter-circles, placed on a grid with random rotations. What makes them interesting is how little it takes to change their character.

![Diagonals in ochre](/media/$M_TESS_OCHRE)

- **Bias** below 50% produces long rivers; above it, closed loops.
- **Hatching** turns a line drawing into an engraving: concentric arcs inside each tile.
- A three-colour palette is enough. Paper, night and ochre cover most prints.

Tessera is in the Studio plan. Subscribers can [see the plans](/pricing).
EOF
)" "$M_TESS_ARCS" "$C_RAMON" '["tessera","design"]' yes
post plans-and-free-samples "Plans, demos and free samples" \
  "Three ways in: try a demo, download a sample, or subscribe." "$(cat <<'EOF'
We want people to try things before paying for them, so there are three ways in:

1. **Demos**: a private instance for 30 minutes, no account.
2. **Free samples**: some releases are downloadable as a single HTML file.
3. **Plans**: *Subscriber* runs every regular application; *Studio* adds the heavier tools and more credits.

Subscriptions follow you: cancel and your instances stay, but they stop launching.
EOF
)" "" "$C_MANUEL" '["news"]' yes
post designing-the-studio "Designing the studio (draft)" \
  "Notes on the editor we use to publish these pages." "This post is still a **draft**. It only appears in the studio." "" "$C_RAMON" '["notes"]' no
echo done
